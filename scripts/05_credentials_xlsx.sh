#!/usr/bin/env bash
# Runs ON THE SOURCE. Builds ~/migration_credentials_<site>_<date>.xlsx (chmod 600) with every login
# involved in the migration: servers, bench users, MariaDB root, generated site DB users, encryption keys.
set -euo pipefail
source "$(dirname "$0")/../config.env"
OUT=~/migration_credentials_${TARGET_SITE}_$(date +%Y%m%d).xlsx
SRC_IP=$(hostname -I | awk '{print $1}')

# site_config values (generated DB user/password, encryption_key) from both ends
TGT_CFG=$(ssh "${TARGET_USER}@${TARGET_HOST}" "cat ${TARGET_BENCH}/sites/${TARGET_SITE}/site_config.json")
SRC_CFG=$(cat "${SRC_BENCH}/sites/${SRC_SITE}/site_config.json")

umask 077
export OUT SRC_IP TGT_CFG SRC_CFG TARGET_HOST TARGET_ROOT_PASS TARGET_USER TARGET_USER_PASS TARGET_DB_ROOT_PASS \
  TARGET_SITE SRC_SITE SRC_HOST_LABEL SRC_USER SRC_USER_PASS SRC_DB_ROOT_USER SRC_DB_ROOT_PASS
"${SRC_BENCH}/env/bin/python" -I - <<'PY'
import json, os
from datetime import date
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill
from openpyxl.utils import get_column_letter

e = os.environ
t, s = json.loads(e["TGT_CFG"]), json.loads(e["SRC_CFG"])
new, old = f"NEW {e['TARGET_HOST']}", f"OLD {e['SRC_IP']}"
rows = [
  # server, purpose, username, password, how to use / notes
  (new, "SSH - root", "root", e["TARGET_ROOT_PASS"], f"ssh root@{e['TARGET_HOST']}  (SSH key from source also works)"),
  (new, "SSH - bench user (use this for remote access)", e["TARGET_USER"], e["TARGET_USER_PASS"],
   f"ssh {e['TARGET_USER']}@{e['TARGET_HOST']}  - has sudo; same password for sudo"),
  (new, "MariaDB root", "root", e["TARGET_DB_ROOT_PASS"], "mysql -uroot -p  (needed for bench new-site / restore / drop-site)"),
  (new, f"MariaDB - site DB user ({e['TARGET_SITE']})", t.get("db_name", ""), t.get("db_password", ""),
   f"generated by bench new-site; database name = {t.get('db_name','')}; stored in sites/{e['TARGET_SITE']}/site_config.json"),
  (new, f"ERP web login ({e['TARGET_SITE']})", "Administrator", "(same as on old site)",
   f"http://{e['TARGET_HOST']}  - restored from {e['SRC_SITE']} backup; all ERP users keep their old passwords"),
  (new, f"Site encryption_key ({e['TARGET_SITE']})", "-", t.get("encryption_key", ""),
   "copied from source; needed to decrypt stored passwords if you ever restore a backup elsewhere"),
  (old, "SSH - bench user", e["SRC_USER"], e["SRC_USER_PASS"], f"{e['SRC_HOST_LABEL']}; has sudo"),
  (old, "MariaDB root", e["SRC_DB_ROOT_USER"], e["SRC_DB_ROOT_PASS"], ""),
  (old, f"MariaDB - site DB user ({e['SRC_SITE']})", s.get("db_name", ""), s.get("db_password", ""),
   f"database name = {s.get('db_name','')}"),
  (old, f"Site encryption_key ({e['SRC_SITE']})", "-", s.get("encryption_key", ""), "same value as the new site"),
  (old, "SSH key used for migration", e["SRC_USER"], "(no passphrase)",
   "~/.ssh/id_ed25519 on the old server; authorised for root and the bench user on the new server"),
]
wb = Workbook(); ws = wb.active; ws.title = "Credentials"
hdr = ("Server", "Purpose", "Username", "Password", "Notes")
ws.append(hdr)
for r in rows: ws.append(r)
for c in ws[1]:
    c.font = Font(bold=True, color="FFFFFF"); c.fill = PatternFill("solid", fgColor="305496")
for i, w in enumerate((22, 42, 22, 36, 90), 1): ws.column_dimensions[get_column_letter(i)].width = w
ws.freeze_panes = "A2"
ws.append(()); ws.append((f"Generated {date.today()}  - delete from the server after downloading; rotate passwords that were shared in chat.",))
wb.save(e["OUT"])
print("wrote", e["OUT"], f"({len(rows)} rows)")
PY
chmod 600 "$OUT"
echo "download: scp ${SRC_USER}@${SRC_IP}:${OUT} ."
